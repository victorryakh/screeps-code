/**
 * Генерирует внутриигровые пиксели, если у процессорного bucket достаточно
 * запаса. Вызывается один раз в тик из {@link loop} сразу после основного
 * прохода, чтобы не конкурировать с боевой логикой за CPU.
 *
 * @remarks
 * Пиксели — внутриигровая валюта, расходуемая исключительно на косметические
 * покупки (декор), то есть на игровой процесс они не влияют. Поэтому выпуск
 * пикселей включается только при `Game.cpu.bucket >= 10000`, что соответствует
 * полному CPU-ливоту с большим запасом: бот «копит» ресурсы во время простоя
 * и не жертвует ими ради косметики.
 *
 * @returns Ничего; при ошибках окружения (отсутствие `Game.cpu` или
 *          метода `generatePixel`) функция тихо завершается.
 */
export function generatePixel(): void {
    if (
        Game.cpu &&
        Game.cpu.bucket >= 10000 &&
        typeof Game.cpu.generatePixel === 'function'
    ) {
        Game.cpu.generatePixel();
    }
}
