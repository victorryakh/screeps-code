/* ============================================================================
 * Роль `harvester`: добыча энергии и снабжение spawn/extension/tower.
 *
 * Тело: [WORK, CARRY, CARRY, MOVE, MOVE] (минимально достаточное).
 * Цикл:
 *   1. Найти хранилище, которое может принять энергию, и посчитать груз
 *      рейса (см. `deliveryTripLoad`).
 *   2. Если в рюкзаке уже есть этот груз — сдать энергию в хранилище.
 *   3. Иначе — добыть недостающее: с `memory.sourceId` (если задан) или
 *      с ближайшего активного источника.
 *   4. Если хранилища нет (комната переполнена) и рюкзак полон —
 *      апгрейдить контроллер (харвестер выполняет роль «последнего
 *      рубежа» экономики).
 *   5. В любом случае, если контроллер в зоне апгрейда (дистанция 3) —
 *      качать его тем, что есть в рюкзаке (см. `upgradeControllerInPlace`).
 *
 * Ключевое правило: харвестер возит ровно столько энергии, сколько
 * принимает хранилище, и возвращается к источнику с пустым рюкзаком.
 * Набитый рюкзак при узком хранилище означает, что половина энергии
 * едет обратно вхолостую, а усталость за это платит крип.
 * ==========================================================================*/

import {
    harvestEnergy,
    findClosestSource,
    transferEnergy,
    findEnergyTransferTarget,
    deliveryTripLoad,
    upgradeRoomController,
    upgradeControllerInPlace,
    withdrawEnergy,
    findNearestEnergyDonor,
    runStepAside
} from '../utilities';
import { DELIVERY_MIN_TRIP } from '../constants';

/**
 * Аварийный режим спасательного харвестера.
 *
 * @remarks
 * Спасательный крип появляется в комнате, у которой не осталось ни одного
 * рабочего: спавн не может оплатить обычное тело, а энергия в комнате лежит
 * в расширениях, до которых спавн не дотягивается. Такая комната не может
 * заказать крипа никогда — `spawnCreep` берёт энергию из самого спавна, а
 * спавн не регенерирует, пока энергии в спавне и расширениях комнаты больше
 * 300.
 *
 * Поэтому задача спасателя простая и не про добычу: перенести уже добытую
 * энергию из расширения в спавн. Энергия источника нужна нормальным
 * харвестерам, а энергия расширения лежит без дела: до спавна её никто не
 * донесёт.
 *
 * @param creep Спасательный крип.
 * @returns `true`, если крип занят спасением; `false` — если спасать больше
 *          нечего и крип должен вернуться к обычной работе.
 */
function runRescue(creep: Creep): boolean {
    const spawn = creep.room.find(FIND_MY_SPAWNS)[0];

    if (!spawn) {
        return false;
    }

    if (spawn.store.getFreeCapacity(RESOURCE_ENERGY) <= 0) {
        // Спавн полон — задача выполнена, крип работает как обычный.
        delete creep.memory.rescue;

        return false;
    }

    if (creep.store[RESOURCE_ENERGY] > 0) {
        // Несём добытое в спавн.
        transferEnergy(creep, spawn, {
            visualizePathStyle: { stroke: '#ffaa00' }
        });

        return true;
    }

    const donor = findNearestEnergyDonor(creep);

    if (!donor) {
        // Доноров нет — спасать нечего, работаем как обычный харвестер.
        delete creep.memory.rescue;

        return false;
    }

    withdrawEnergy(creep, donor, {
        visualizePathStyle: { stroke: '#ffaa00' }
    });

    return true;
}

/**
 * Выполняет один шаг harvester-а. См. описание модуля.
 *
 * @param creep Крип с `role === ROLE.HARVESTER`. Назначенный источник
 *              хранится в `creep.memory.sourceId` (проставляется при
 *              спавне через `_harvesterIndex`).
 */
export function run(creep: Creep): void {
    // Спасательный режим: крип переносит энергию из расширений в спавн.
    // Это единственный способ запустить комнату, у которой в спавне меньше
    // энергии, чем стоит любое обычное тело.
    if (creep.memory.rescue && runRescue(creep)) {
        return;
    }

    // Сдвиг в сторону — исключение из правил роли, но только когда рюкзак
    // пуст: нести энергию в сторону бессмысленно, рейс пропадёт (см.
    // `ensureCreepsNotConfined` в `room.ts`).
    if (creep.store[RESOURCE_ENERGY] === 0 && runStepAside(creep)) {
        return;
    }

    const transferTarget = findEnergyTransferTarget(creep, [
        STRUCTURE_SPAWN,
        STRUCTURE_EXTENSION,
        STRUCTURE_TOWER,
        STRUCTURE_CONTAINER,
        STRUCTURE_STORAGE
    ]);

    // Груз рейса — ёмкость хранилища, ограниченная ёмкостью рюкзака.
    //
    // Условие сдачи «в рюкзаке не меньше груза рейса» недостижимо, если
    // харвестер параллельно качает контроллер: апгрейд на месте съедает
    // одну энергию за тик, добыча даёт две, и к началу тика рюкзак стоит
    // ровно на единицу ниже груза рейса.
    //
    // В E34S53 это и случилось: три харвестера стояли с рюкзаками по 99 из
    // 100 и никогда не сдавали энергию. Источник при этом исправно
    // опустошался, а в спавне и расширениях не менялось ничего сутками:
    // энергия уходила в контроллер мимо структур. Комната не получала
    // дохода, спавн не мог оплатить замену умирающих крипов, и колония
    // стояла в одном шаге от гибели.
    //
    // Поэтому сдаём, как только в рюкзаке есть половина рейса: рейс
    // короче, харвестер быстрее возвращается к источнику, а доход
    // комнаты появляется.
    const tripLoad = transferTarget ? deliveryTripLoad(creep, transferTarget) : 0;
    const deliverAt = transferTarget ? Math.min(tripLoad, DELIVERY_MIN_TRIP) : 0;

    if (transferTarget && creep.store[RESOURCE_ENERGY] >= deliverAt) {
        // Энергии хватает на рейс — сдаём. Ждать, пока наберётся весь
        // рюкзак, не нужно: лишнее хранилище всё равно не примет, а крип
        // нёс лишнее обратно к источнику и платит за дорогу усталостью.
        transferEnergy(creep, transferTarget, {
            visualizePathStyle: { stroke: '#ffffff' }
        });

        // В тике сдачи контроллер не качаем: эта энергия нужна в
        // структуре. Иначе харвестер забирает из своего рюкзака ровно
        // столько, сколько только что сдал, — и комната снова остаётся
        // без дохода.
        return;
    }

    if (!transferTarget && creep.store[RESOURCE_ENERGY] > 0) {
        // Сдать энергию некуда (комната переполнена), а в рюкзаке что-то
        // есть: качаем контроллер — энергия в рюкзаке всё равно пропадёт.
        //
        // Раньше условие было «рюкзак полон» (`getFreeCapacity() === 0`),
        // и это стоило комнате половины дохода: рюкзак на 100 мест полон
        // только при 100 энергии, а харвестер с 99 энергией в рюкзаке
        // считался «не полным» — он снова шёл к источнику, добывал одну
        // энергию, и только потом качал контроллер. Итог: тик добычи
        // чередовался с тиком апгрейда, доход падал вдвое, а прогресс
        // контроллера — тоже. Энергия, которую комната не может сложить в
        // структуры, идёт в контроллер: там ей нет альтернативы.
        upgradeRoomController(creep, {
            visualizePathStyle: { stroke: '#ffffff' }
        });

        return;
    }

    let source = Game.getObjectById(creep.memory.sourceId ?? ('' as Id<Source>));

    if (!source) {
        source = findClosestSource(creep);
    }

    if (!source) {
        return;
    }

    // Добыча и апгрейд в одном тике. Движок не ставит между интентами
    // `harvest` и `upgradeController` взаимного приоритета, а источник
    // даёт 2 энергии за тик на часть WORK, тогда как апгрейд забирает 1.
    // Значит крип на клетке добычи может качать контроллер, не сходя с
    // неё: ровно та энергия, которая иначе ехала бы в контейнер, и потом —
    // вторым рейсом, уже силами апгрейдера — к контроллеру.
    //
    // Это главный рычаг экономики комнаты, которой до следующего уровня
    // контроллера нужны сотни тысяч единиц прогресса: энергия, сданная в
    // структуру, до контроллера ещё не дошла, а энергия, оставленная в
    // рюкзаке на клетке добычи, легла в контроллер сразу.
    //
    // **Но апгрейд на месте нельзя делать, когда рюкзак перестаёт расти.**
    // Добыча даёт `min(2, свободное место)`, апгрейд забирает 1. Если свободно
    // одно место, добыча даёт 1 и апгрейд забирает 1 — рюкзак не растёт ни на
    // единицу, и крип вечно стоит в одной энергии от порога сдачи.
    //
    // Для тела с рюкзаком на 100 это не проявляется: порог сдачи — 50, и до
    // него крип дотягивается с запасом. Для **спасательного** тела (рюкзак 50)
    // порог сдачи равен ёмкости рюкзака, и без этого правила крип **никогда**
    // не сдаёт энергию. Именно так и стоял харвестер E34S53 с 49 из 50:
    // источник исправно опустошался, а спавн не получал ни единицы энергии —
    // и третий крип так и не появился.
    const freeBefore = creep.store.getFreeCapacity(RESOURCE_ENERGY);

    harvestEnergy(creep, source, {
        visualizePathStyle: { stroke: '#ffaa00' }
    });

    if (freeBefore > 1) {
        upgradeControllerInPlace(creep);
    }
}
