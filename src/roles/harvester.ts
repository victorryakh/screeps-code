/* ============================================================================
 * Роль `harvester`: добыча энергии и снабжение spawn/extension/tower.
 *
 * Тело: [WORK, CARRY, CARRY, MOVE, MOVE] (минимально достаточное).
 * Цикл:
 *   1. Найти хранилище, которое может принять энергию, и посчитать груз
 *      рейса (см. `deliveryTripLoad`).
 *   2. Если в рюкзаке уже есть этот груз — сдать энергию в хранилище.
 *   3. Иначе — добыть недостающее: с `memory.sourceId` (если задан) или
 *      с ближайшего активного источника.
 *   4. Если хранилища нет (комната переполнена) и рюкзак полон —
 *      апгрейдить контроллер (харвестер выполняет роль «последнего
 *      рубежа» экономики).
 *   5. В любом случае, если контроллер в зоне апгрейда (дистанция 3) —
 *      качать его тем, что есть в рюкзаке (см. `upgradeControllerInPlace`).
 *
 * Ключевое правило: харвестер возит ровно столько энергии, сколько
 * принимает хранилище, и возвращается к источнику с пустым рюкзаком.
 * Набитый рюкзак при узком хранилище означает, что половина энергии
 * едет обратно вхолостую, а усталость за это платит крип.
 * ==========================================================================*/

import {
    harvestEnergy,
    findClosestSource,
    transferEnergy,
    findEnergyTransferTarget,
    deliveryTripLoad,
    reachableLoad,
    upgradeControllerInPlace,
    withdrawEnergy,
    findNearestEnergyDonor,
    runStepAside
} from '../utilities';

/**
 * Аварийный режим спасательного харвестера.
 *
 * @remarks
 * Спасательный крип появляется в комнате, которая больше не производит
 * энергию: в спавнах и расширениях вместе меньше, чем стоит обычное тело,
 * а добывать больше некому. Такая комната не может заказать крипа никогда —
 * и энергию в спавн ей больше никто не принесёт.
 *
 * Поэтому задача спасателя простая и не про добычу: перенести уже добытую
 * энергию из расширения в спавн. Энергия источника нужна нормальным
 * харвестерам, а энергия расширения лежит без дела: до спавна её никто не
 * донесёт.
 *
 * Для этого WORK не нужен — достаточно CARRY и MOVE, поэтому спасателем
 * может быть и тело `[CARRY, MOVE]` (грузчик).
 *
 * @param creep Спасательный крип.
 * @returns `true`, если крип занят спасением; `false` — если спасать больше
 *          нечего и крип должен вернуться к обычной работе.
 */
function runRescue(creep: Creep): boolean {
    const spawn = creep.room.find(FIND_MY_SPAWNS)[0];

    if (!spawn) {
        return false;
    }

    if (spawn.store.getFreeCapacity(RESOURCE_ENERGY) <= 0) {
        // Спавн полон — задача выполнена, крип работает как обычный.
        delete creep.memory.rescue;

        return false;
    }

    if (creep.store[RESOURCE_ENERGY] > 0) {
        // Несём добытое в спавн.
        transferEnergy(creep, spawn, {
            visualizePathStyle: { stroke: '#ffaa00' }
        });

        return true;
    }

    const donor = findNearestEnergyDonor(creep);

    if (!donor) {
        // Доноров нет — спасать нечего, работаем как обычный харвестер.
        delete creep.memory.rescue;

        return false;
    }

    withdrawEnergy(creep, donor, {
        visualizePathStyle: { stroke: '#ffaa00' }
    });

    return true;
}

/**
 * Выполняет один шаг harvester-а. См. описание модуля.
 *
 * @param creep Крип с `role === ROLE.HARVESTER`. Назначенный источник
 *              хранится в `creep.memory.sourceId` (проставляется при
 *              спавне через `_harvesterIndex`).
 */
export function run(creep: Creep): void {
    // Спасательный режим: крип переносит энергию из расширений в спавн.
    // Это единственный способ запустить комнату, у которой в спавне меньше
    // энергии, чем стоит любое обычное тело.
    if (creep.memory.rescue && runRescue(creep)) {
        return;
    }

    // Сдвиг в сторону — исключение из правил роли, но только когда рюкзак
    // пуст: нести энергию в сторону бессмысленно, рейс пропадёт (см.
    // `ensureCreepsNotConfined` в `room.ts`).
    if (creep.store[RESOURCE_ENERGY] === 0 && runStepAside(creep)) {
        return;
    }

    let transferTarget = findEnergyTransferTarget(creep, [
        STRUCTURE_SPAWN,
        STRUCTURE_EXTENSION,
        STRUCTURE_TOWER,
        STRUCTURE_CONTAINER,
        STRUCTURE_STORAGE
    ]);

    // Груз рейса — ёмкость хранилища, ограниченная ёмкостью рюкзака.
    //
    // Порог сдачи — **столько, сколько харвестер реально может накопить**.
    //
    // Пока харвестер качает контроллер на месте, его рюкзак упирается не в
    // свою ёмкость, а в `ёмкость − WORK`: апгрейд на месте забирает из
    // рюкзака по одной энергии на часть WORK за тик, а добыча даёт по две.
    // С телом [WORK, WORK, CARRY, MOVE] это 48 из 50, и рюкзак растёт на 2 за
    // тик ровно до этой отметки.
    //
    // Условие сдачи «в рюкзаке не меньше груза рейса» (50) при этом
    // **недостижимо никогда** — до 50 рюкзак не дойдёт.
    //
    // В E34S53 это стоило комнате всего дохода (26.11.2026): три харвестера
    // стояли на клетках добычи с рюкзаками по 48 из 50 и **никогда не сдавали
    // энергию**. Источник опустошался на 8 энергий в тик, в контроллер уходило
    // 4, а 2 энергии в тик падали на пол и там сгнивали. Расширения стояли
    // пустыми, билдер не мог взять энергию (доноры — расширения, а спавн
    // исключён) и стоял у клетки апгрейда, контейнер не строился, апгрейдер
    // не появлялся: бюджет комнаты был ноль. Круг замкнулся: энергии в
    // структурах нет — значит, расширения пусты — значит, билдер стоит —
    // значит, доставки нет.
    //
    // Порог, равный достижимому запасу, решает и вторую половину проблемы:
    // до него рюкзак не полон, а значит, добыча не выбрасывает излишек на
    // пол. Рейс при этом остаётся полным — груз рейса ограничен рюкзаком, а
    // не половиной рюкзака, — значит, дорога до хранилища оплачивается один
    // раз на 50 энергий, а не на 25.
    const tripLoad = transferTarget ? deliveryTripLoad(creep, transferTarget) : 0;
    const deliverAt = transferTarget
        ? Math.max(1, Math.min(tripLoad, reachableLoad(creep)))
        : 0;

    if (transferTarget && creep.store[RESOURCE_ENERGY] >= deliverAt) {
        // Энергии хватает на рейс — сдаём. Ждать, пока наберётся весь
        // рюкзак, не нужно: лишнее хранилище всё равно не примет, а крип
        // нёс лишнее обратно к источнику и платит за дорогу усталостью.
        const before = creep.store[RESOURCE_ENERGY];
        const inRange =
            Math.max(
                Math.abs(creep.pos.x - transferTarget.pos.x),
                Math.abs(creep.pos.y - transferTarget.pos.y)
            ) <= 1;

        const result = transferEnergy(creep, transferTarget, {
            visualizePathStyle: { stroke: '#ffffff' }
        });

        // Сдача не вышла, хотя крип стоял вплотную к цели: хранилище переполнилось
        // или сдаче что-то помешало. Тогда цель надо забыть — иначе крип будет
        // ходить к ней снова и снова с полным рюкзаком.
        //
        // В E34S53 (20.11.2026) харвестер так и ходил кругами по полурумью с
        // полным рюкзаком минуты подряд: цель была в шаге по геометрии, но
        // недостижима — клетки добычи заняли наши же крипы, и движок вёл его
        // в обход всей комнаты.
        if (inRange && creep.store[RESOURCE_ENERGY] >= before) {
            delete creep.memory._deliveryTarget;
        }

        // **До цели не дойти.** Движок вернул `ERR_NO_PATH`: коридор
        // перекрыт нашим же крипом (крипы — препятствия для движения), и
        // маршрут, который бот считал, физически не существует.
        //
        // Раньше этот код просто игнорировался, и харвестер **замирал
        // навсегда**: ветка сдачи возвращала управление немедленно, поэтому
        // крип не добывал и не качал контроллер — он стоял с полным
        // рюкзаком на клетке добычи и занимал её.
        //
        // В E34S53 (24.11.2026) так стоял харвестер на (20,23): клетки
        // добычи вытянуты в цепочку шириной в одну клетку, башни закрывают
        // восточный обход, и клетка (20,23) достижима только через (20,22) —
        // а её занял другой харвестер. Третий крип стоял с полным рюкзаком и
        // не делал ничего: комната теряла треть добычи, а её заодно держал
        // запертый намертво слот у источника.
        //
        // Правильный вывод: если до цели не дойти — цель негодная.
        // Забываем её и работаем на месте: клетка добычи никуда не денется,
        // а энергия пойдёт в контроллер (см. `upgradeControllerInPlace`).
        if (result === ERR_NO_PATH) {
            delete creep.memory._deliveryTarget;
            transferTarget = null;
        } else {
            // В тике сдачи контроллер не качаем: эта энергия нужна в
            // структуре. Иначе харвестер забирает из своего рюкзака ровно
            // столько, сколько только что сдал, — и комната снова остаётся
            // без дохода.
            return;
        }
    }

    // Сдавать некуда — рядом с клеткой добычи нет свободного места, и
    // энергия рюкзака идёт в контроллер на месте (см.
    // `upgradeControllerInPlace` ниже).
    //
    // Раньше здесь стоял `return`, и харвестер на этом останавливался
    // совсем: он не возвращался на клетку добычи и стоял с полным рюкзаком,
    // пока тот не пустел. В E34S53 (23.11.2026) так харвестер на (20,24)
    // простоял на (20,26) — на кольце рождения вокруг спавна, — не добывая
    // ничего: доход комнаты упал с 4.0 до 2.0 энергии в тик.
    //
    // Прежнее условие «рюкзак полон» (`getFreeCapacity() === 0`) стоило
    // комнате половины дохода: рюкзак на 100 мест полон только при 100
    // энергии, а харвестер с 99 энергией в рюкзаке считался «не полным» —
    // он снова шёл к источнику, добывал одну энергию, и только потом качал
    // контроллер. Итог: тик добычи чередовался с тиком апгрейда, доход
    // падал вдвое, а прогресс контроллера — тоже. Энергия, которую комната
    // не может сложить в структуры, идёт в контроллер: там ей нет
    // альтернативы.
    const withoutTarget = !transferTarget;

    let source = Game.getObjectById(creep.memory.sourceId ?? ('' as Id<Source>));

    if (!source) {
        source = findClosestSource(creep);
    }

    if (!source) {
        return;
    }

    // Добыча и апгрейд в одном тике. Движок не ставит между интентами
    // `harvest` и `upgradeController` взаимного приоритета, а источник
    // даёт 2 энергии за тик на часть WORK, тогда как апгрейд забирает 1.
    // Значит крип на клетке добычи может качать контроллер, не сходя с
    // неё: ровно та энергия, которая иначе ехала бы в контейнер, и потом —
    // вторым рейсом, уже силами апгрейдера — к контроллеру.
    //
    // Это главный рычаг экономики комнаты, которой до следующего уровня
    // контроллера нужны сотни тысяч единиц прогресса: энергия, сданная в
    // структуру, до контроллера ещё не дошла, а энергия, оставленная в
    // рюкзаке на клетке добычи, легла в контроллер сразу.
    //
    // **Но апгрейд на месте нельзя делать, когда рюкзак перестаёт расти.**
    // Добыча даёт `min(2, свободное место)`, апгрейд забирает 1. Если свободно
    // одно место, добыча даёт 1 и апгрейд забирает 1 — рюкзак не растёт ни на
    // единицу, и крип вечно стоит в одной энергии от порога сдачи.
    //
    // Для тела с рюкзаком на 100 это не проявляется: порог сдачи — 50, и до
    // него крип дотягивается с запасом. Для **спасательного** тела (рюкзак 50)
    // порог сдачи равен ёмкости рюкзака, и без этого правила крип **никогда**
    // не сдаёт энергию. Именно так и стоял харвестер E34S53 с 49 из 50:
    // источник исправно опустошался, а спавн не получал ни единицы энергии —
    // и третий крип так и не появился.
    const freeBefore = creep.store.getFreeCapacity(RESOURCE_ENERGY);

    harvestEnergy(creep, source, {
        visualizePathStyle: { stroke: '#ffaa00' }
    });

    // Апгрейд на месте, когда сдавать некуда, делается **всегда**, даже с
    // полным рюкзаком: иначе крип застревает (добычи нет — места нет,
    // апгрейд не сделан), и энергия в рюкзаке пропадает зря.
    if (freeBefore > 1 || withoutTarget) {
        upgradeControllerInPlace(creep);
    }
}
