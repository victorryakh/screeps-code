/**
 * Сколько тиков спавн должен оставаться запечатанным, прежде чем бот
 * попытается освободить клетку.
 *
 * @remarks
 * Пауза нужна, чтобы не реагировать на кратковременные состояния: движок
 * может прямо сейчас удалять структуру, и счётчик свободных клеток
 * обновится на следующем тике. Проверка идёт раз в
 * `EXTENSION_CHECK_INTERVAL` (10 тиков), поэтому 30 тиков — это три
 * последовательные проверки.
 *
 * Крипы в проверке **учитываются**: движок не может поставить крипа на
 * клетку, занятую другим крипом (`OBSTACLE_OBJECT_TYPES` включает `creep`),
 * поэтому стоящий крип закрывает клетку рождения ровно так же, как
 * расширение. Из-за этого запечатывание спавна не всегда видно по
 * структурам — а именно так колония простояла лишние сутки.
 */
export const SEALED_SPAWN_HEAL_DELAY = 30;

/**
 * Минимальный интервал (в тиках) между попытками освободить клетку у
 * запечатанного спавна.
 *
 * @remarks
 * Страховка от повреждения: если снос расширения не дал эффекта (движок
 * отказал), бот не должен сносить следующее расширение на каждом
 * `SEALED_SPAWN_HEAL_DELAY` тиков. За одну серию запечатывания сносится не
 * более одного расширения, а следующая попытка возможна не раньше, чем
 * через этот интервал.
 */
export const SEALED_SPAWN_HEAL_RETRY = 1000;

/**
 * Минимальное число свободных клеток рождения вокруг спавна, которое бот
 * старается поддерживать.
 *
 * @remarks
 * Вокруг спавна восемь клеток, и движок ставит крипа на любую свободную из
 * них. Если свободна одна клетка, то достаточно одного вставшего на неё
 * крипа, чтобы спавн перестал работать — колония замирает без ошибок.
 * Три свободные клетки дают запас прочности: покачивание крипов, временная
 * занятость клетки и опоздание с постройкой не убивают спавн.
 *
 * Если свободных клеток меньше минимума, бот сносит расширения в кольце
 * радиуса 1 вокруг спавна (см. `ensureSpawnRingReserve`).
 */
export const SPAWN_BIRTH_TILES_MIN = 3;

/**
 * Минимум свободных клеток рождения, при котором спавн работает надёжно.
 *
 * @remarks
 * Две свободные клетки — это рабочая конфигурация: новорождённый займёт одну,
 * вторая останется, и спавн продолжит работать. Одна свободная клетка — спавн
 * держится на одном крипе: как только этот крип (или только что родившийся)
 * встанет на единственную свободную клетку, спавн запечатывается, и колония
 * замирает без единой ошибки.
 *
 * Порог применяется к свободным клеткам **с учётом крипов**: движок не
 * поставит крипа на клетку, занятую другим крипом, поэтому такая клетка
 * свободной не является.
 */
export const SPAWN_BIRTH_TILES_CRITICAL = 2;

/**
 * Версия правила выбора клетки апгрейда.
 *
 * @remarks
 * Кэш `_upgradeSpot` живёт в памяти крипа дольше одной правки кода: если
 * правило изменилось, старый кэш продолжает уводить крипа в дальнюю клетку.
 * Смена версии заставляет кэш пересчитаться.
 *
 * История:
 * - `1` — клетка рядом с любым донором, расстояние считалось «по прямой»;
 * - `2` — клетка выбирается по длине пути от конкретного донора;
 * - `3` — клетка выбирается по длине пути от клеток добычи: харвестер
 *   приносит энергию туда, и чем ближе апгрейдер к добыче, тем короче
 *   рейс харвестера;
 * - `4` — из кандидатов убраны клетки, занятые живыми крипами: выбор к
 *   клетки не должен зависеть от того, где в этот момент оказался
 *   харвестер.
 */
export const UPGRADE_SPOT_VERSION = 4;
