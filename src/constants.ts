/**
 * Идентификаторы ролей, назначаемых крипам через `Creep.memory.role`.
 *
 * Объект помечен `as const`, чтобы система типов могла вывести литеральный
 * объединённый тип из значений (см. {@link RoleKey}).
 */
export const ROLE = {
    /** Добывает энергию и снабжает спавны/расширения в домашней комнате. */
    HARVESTER: 'harvester',
    /** Передаёт энергию в контроллер комнаты для повышения уровня. */
    UPGRADER: 'upgrader',
    /** Строит объекты на участках строительства по колонии. */
    BUILDER: 'builder',
    /** Чинит повреждённые структуры, отдавая приоритет дорогам и рампатам. */
    REPAIRER: 'repairer',
    /** Добывает энергию в удалённых комнатах за пределами домашней. */
    RHARVESTER: 'rharvester',
    /** Резервирует контроллер нейтральной/удалённой комнаты для доступа к ней. */
    RESERVER: 'reserver',
    /** Захватывает контроллер целевой комнаты для расширения колонии. */
    CLAIMER: 'claimer'
} as const;

/** Объединение всех допустимых строк ролей, выведенное из {@link ROLE}. */
export type RoleKey = (typeof ROLE)[keyof typeof ROLE];

/**
 * Запас прочности (в тиках) до начала даунгрейда контроллера комнаты.
 * Используется логикой апгрейдера, чтобы успеть среагировать до потери прогресса.
 */
export const DOWNGRADE_BUFFER_TICKS = 2000;

/**
 * Доля от максимального количества хитов структуры, ниже которой
 * отправляется ремонтник (диапазон `0..1`).
 */
export const REPAIR_THRESHOLD = 0.8;

/**
 * Срок жизни кэша (в тиках) для поиска выходов `FIND_EXIT`. Большие значения
 * экономят CPU, но дают менее свежие данные при изменении топологии комнаты.
 */
export const EXITS_CACHE_TTL = 5000;

/**
 * Время жизни кэша пути (в тиках) для перемещений внутри домашней комнаты.
 * Небольшое значение, так как расположение объектов в ней часто меняется
 * по мере роста колонии.
 */
export const HOME_PATH_TTL = 25;

/**
 * Время жизни кэша пути (в тиках) для перемещений в удалённых комнатах.
 * Больше, чем {@link HOME_PATH_TTL}, потому что топология удалённых комнат
 * стабильнее и пути длиннее.
 */
export const REMOTE_PATH_TTL = 50;

/**
 * Максимальное расстояние (в клетках) от спавна, в пределах которого
 * может планироваться расширение. Соответствует игровому правилу, что
 * расширения работают в любой точке комнаты, но позволяет удерживать
 * компактную планировку.
 */
export const EXTENSION_PLAN_RADIUS = 6;

/**
 * Интервал (в тиках) между проходами планировщика, проверяющими,
 * нужно ли поставить в очередь строительство дополнительных расширений.
 */
export const EXTENSION_CHECK_INTERVAL = 10;

/**
 * Битовая маска, определяющая непроходимые клетки стен в маске рельефа
 * комнаты. Используется в {@link planBaseLayout} и {@link ensureExtensions}
 * для отсева клеток, на которых нельзя строить расширения.
 *
 * @remarks
 * В оффлайн-окружениях (юнит-тесты, симулятор без полного API)
 * `TERRAIN_MASK_WALL` может быть не определена — в этом случае подставляется
 * числовой литерал `1`, совпадающий со значением константы в рантайме Screeps.
 */
export const WALL_TERRAIN: TERRAIN_MASK_WALL = (typeof TERRAIN_MASK_WALL !== 'undefined') ? TERRAIN_MASK_WALL : 1;
